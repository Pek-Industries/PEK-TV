def dart_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main(out_dir: str) -> None:
    keys = [r[0] for r in ROWS]
    dup = {k for k in keys if keys.count(k) > 1}
    if dup:
        sys.exit(f"duplicate English keys: {sorted(dup)}")
    os.makedirs(out_dir, exist_ok=True)
    for i, code in enumerate(LANGS, start=1):
        lines = [
            "// GENERATED by tools/gen_l10n.py from its table. Edit the table there, then run the script again.",
            "// English is the key (see l10n.dart); a missing entry simply stays English.",
            f"const Map<String, String> strings{code.capitalize()} = {{",
        ]
        for r in ROWS:
            if len(r) != 5:
                sys.exit(f"row has {len(r)} columns: {r[0]}")
            lines.append(f"  {dart_str(r[0])}: {dart_str(r[i])},")
        lines.append("};")
        with open(os.path.join(out_dir, f"l10n_{code}.dart"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    print(f"{len(ROWS)} strings x {len(LANGS)} languages -> {out_dir}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "flutter_ui/lib/src/l10n")
