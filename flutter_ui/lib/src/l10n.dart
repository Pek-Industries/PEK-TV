import 'dart:ui' as ui;

import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';

import 'l10n/l10n_de.dart';
import 'l10n/l10n_es.dart';
import 'l10n/l10n_fr.dart';
import 'l10n/l10n_pt.dart';
import 'refresh.dart';
import 'store.dart';

/// One language the app can show.
class AppLanguage {
  const AppLanguage(this.code, this.nativeName, this.englishName);

  /// ISO 639-1 code ('en', 'es' ...).
  final String code;

  /// The language's name in that language, so a person can find it whatever the app currently shows.
  final String nativeName;
  final String englishName;
}

/// The app's language.
///
/// **How text is translated.** The English text itself is the key: `'Sign in later'.tr`. A string with no entry for the chosen
/// language simply stays English, so the UI can be translated screen by screen without ever showing a blank or a key name. The
/// tables are in `l10n/l10n_<code>.dart` and are generated by `tools/gen_l10n.py`. Text with a number in it uses a placeholder:
/// `'{n} new'.trp({'n': 3})`.
///
/// **What it does not translate.** Titles, synopses and names that come from the library, TMDb or plugins, and plugin / skin text.
///
/// The choice is kept on the device (not per profile) under `pek_language_v1`: 'system' or a code from [languages].
class L10n {
  L10n._();

  static const system = 'system';
  static const _k = 'pek_language_v1';

  /// Right-to-left languages are not offered yet: the D-pad navigation and the skin layouts assume left-to-right.
  static const languages = <AppLanguage>[
    AppLanguage('en', 'English', 'English'),
    AppLanguage('es', 'Español', 'Spanish'),
    AppLanguage('fr', 'Français', 'French'),
    AppLanguage('de', 'Deutsch', 'German'),
    AppLanguage('pt', 'Português', 'Portuguese'),
  ];

  static const Map<String, Map<String, String>> tables = {'es': stringsEs, 'fr': stringsFr, 'de': stringsDe, 'pt': stringsPt};

  /// What the person picked: [system] or a language code. Listen to it to repaint when it changes.
  static final ValueNotifier<String> choice = ValueNotifier<String>(system);
  static String _active = 'en';

  /// The language text is shown in right now ('system' already resolved to the device's language, or English).
  static String get active => _active;

  /// Whether the person has picked a language (including "System default") on this device. The first-launch flow asks until then.
  static bool get chosen => Store.strGet(_k, scoped: false) != null;

  /// The locale for MaterialApp: null follows the device.
  static Locale? get locale => choice.value == system ? null : Locale(_active);
  static List<Locale> get supportedLocales => [for (final l in languages) Locale(l.code)];

  /// Reads the saved choice. Call once, right after [Store.init].
  static void init() {
    final saved = Store.strGet(_k, scoped: false);
    choice.value = _valid(saved) ? saved! : system;
    _active = resolve(choice.value, ui.PlatformDispatcher.instance.locale.languageCode);
  }

  static bool _valid(String? c) => c != null && (c == system || languages.any((l) => l.code == c));

  /// The language to show for [choice] on a device whose language is [deviceCode]. Pure, so it can be tested.
  static String resolve(String choice, String deviceCode) {
    if (choice != system) return languages.any((l) => l.code == choice) ? choice : 'en';
    return languages.any((l) => l.code == deviceCode) ? deviceCode : 'en';
  }

  /// Saves the choice and repaints the whole app in the new language straight away (pages that are open stay open).
  static Future<void> set(String code) async {
    if (!_valid(code)) return;
    await Store.strSet(_k, code, scoped: false);
    final next = resolve(code, ui.PlatformDispatcher.instance.locale.languageCode);
    if (choice.value == code && _active == next) return;
    choice.value = code;
    _active = next;
    refreshWholeApp();
  }

  /// Tests only: show text in [code] without touching the saved choice.
  @visibleForTesting
  static void useForTest(String code) => _active = code;

  /// [en] in the active language, or [en] itself when there is no translation.
  static String tr(String en) {
    if (_active == 'en') return en;
    return tables[_active]?[en] ?? en;
  }

  /// [tr] with `{name}` placeholders filled in.
  static String trp(String en, Map<String, Object> args) {
    var s = tr(en);
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }
}

extension PekTranslate on String {
  /// This English text in the app's language (see [L10n]).
  String get tr => L10n.tr(this);

  /// Same, with `{name}` placeholders filled in.
  String trp(Map<String, Object> args) => L10n.trp(this, args);
}
