#!/usr/bin/env bash
# Collects what the Windows app ships next to its exe into build/windows_stage/ (everything but the Flutter build itself):
#   hesper/{plugins,skins,cacert.pem,.build_stamp}, python/ (embeddable Python + PEK modules), voice/stt/, pek_server.dll,
#   libmpv-2.dll, ffprobe.exe, version.txt.
# Usage: stage-assets.sh <version name>      Needs windows/{libmpv,ffmpeg,python-embed} (fetch-*.sh) and build/backend/pek_server.dll.
# Same rules as the Android workflow's "Stage app assets" step: official plugins are signed with PEK_PLUGIN_SIGNING_KEY.
set -euo pipefail
VERSION="${1:?version name}"
BUILD_TYPE="${BUILD_TYPE:-debug}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PY="$(command -v python3 || command -v python)"
S="$ROOT/build/windows_stage"
rm -rf "$S"
mkdir -p "$S/hesper" "$S/python" "$S/voice"

cp -r "$ROOT/plugins" "$ROOT/skins" "$S/hesper/"
curl -fsSL --retry 5 --retry-all-errors https://curl.se/ca/cacert.pem -o "$S/hesper/cacert.pem"
find "$S/hesper" -name __pycache__ -type d -prune -exec rm -rf {} +
rm -rf "$S"/hesper/plugins/*/data

OFFICIAL="weather tmdb-discover skin-maker"
if [ -n "${PEK_PLUGIN_SIGNING_KEY:-}" ]; then
  for d in $OFFICIAL; do
    [ -d "$S/hesper/plugins/$d" ] || continue
    "$PY" "$ROOT/tools/pektool.py" --no-color sign "$S/hesper/plugins/$d" --key-env PEK_PLUGIN_SIGNING_KEY
  done
  "$PY" "$ROOT/tools/pektool.py" --no-color verify-sig $(for d in $OFFICIAL; do [ -d "$S/hesper/plugins/$d" ] && echo "$S/hesper/plugins/$d"; done) \
    || { echo "::error::The signed plugins do not verify against backend/pek_official_keys.txt - is PEK_PLUGIN_SIGNING_KEY the private half of that key?"; exit 1; }
elif [ "$BUILD_TYPE" = release ]; then
  echo "::error::PEK_PLUGIN_SIGNING_KEY is not set. A release without signed official plugins would ship a Weather plugin that is not trusted. See UPDATES.md (Signing)."
  exit 1
else
  echo "::warning::PEK_PLUGIN_SIGNING_KEY is not set: this debug build's official plugins are unsigned, so Weather runs sandboxed."
fi
echo "$VERSION-$(date -u +%Y%m%d%H%M%S)" > "$S/hesper/.build_stamp"

# Python: the embeddable runtime plus the modules the plugin host needs. pek_runner / pek_flutter / pek_ui / pek_epg / pek_providers are
# the same files the Android app uses (android/app/src/main/python); pek_guard / pek_ed25519 are the shared backend ones.
cp -r "$ROOT/windows/python-embed/." "$S/python/"
P="$S/python/pek"
mkdir -p "$P"
for f in pek_runner pek_flutter pek_ui pek_epg pek_providers; do cp "$ROOT/android/app/src/main/python/$f.py" "$P/"; done
cp "$ROOT/backend/pek_guard.py" "$ROOT/backend/pek_ed25519.py" "$ROOT/windows/python/pek_host.py" "$P/"
"$PY" - "$ROOT/backend/pek_official_keys.txt" "$P/pek_official_keys.py" <<'PY'
import re, sys
keys = []
for line in open(sys.argv[1], encoding="utf-8"):
    line = re.sub(r"#.*$", "", line).strip()
    if re.fullmatch(r"[0-9a-fA-F]{64}", line):
        keys.append(line)
open(sys.argv[2], "w", encoding="utf-8").write("# generated by windows/scripts/stage-assets.sh from backend/pek_official_keys.txt - do not edit\nKEYS = [" + ", ".join("'%s'" % k for k in keys) + "]\n")
PY

# Speech model (bundled, like the APK): tools/fetch-voice-model.sh puts it in assets/bundled/voice/stt.
mkdir -p "$S/voice/stt"
cp "$ROOT"/assets/bundled/voice/stt/* "$S/voice/stt/"

cp "$ROOT/build/backend/pek_server.dll" "$S/"
cp "$ROOT/windows/libmpv/libmpv-2.dll" "$S/"
cp "$ROOT/windows/ffmpeg/ffprobe.exe" "$S/"
echo "$VERSION" > "$S/version.txt"
echo "$S"
